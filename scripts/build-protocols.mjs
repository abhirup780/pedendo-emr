// Turns the guideline protocol files in reference-data/protocols/ into src/lib/protocol-data.ts.
// Run: npm run build:protocols   (after editing or adding a JSON file there)
//
// The JSON files are the record of what was taken from which guideline. Nothing is added
// here: this only drops fields the app does not use and refuses anything malformed.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const dir = new URL('../reference-data/protocols/', import.meta.url)
const out = []
for (const file of readdirSync(dir).filter((f) => f.endsWith('.json')).sort()) {
  const group = JSON.parse(readFileSync(new URL(file, dir), 'utf8'))
  for (const c of group.conditions) {
    const need = (ok, what) => {
      if (!ok) throw new Error(`${file} / ${c.key}: ${what}`)
    }
    need(/^[a-z0-9-]+$/.test(c.key), 'key must be kebab-case')
    need(c.sources.length > 0, 'no sources')
    const ids = new Set(c.sources.map((s) => s.id))
    const cite = (list) => {
      need(Array.isArray(list) && list.every((i) => ids.has(i)), `unknown source id in ${JSON.stringify(list)}`)
      return list
    }
    out.push({
      key: c.key,
      name: c.name,
      group: group.group,
      aliases: c.tag_aliases,
      compiledOn: group.compiled_on,
      review: group.review,
      sources: c.sources.map((s) => ({ id: s.id, org: s.org, year: s.year, title: s.title, url: s.url })),
      sets: c.investigation_sets.map((s) => ({
        name: s.name,
        when: s.when,
        items: s.items.map((i) => ({ test: i.test, category: i.category, unit: i.unit ?? '', note: i.note ?? '', sources: cite(i.source_ids) })),
      })),
      medicines: c.medicines.map((m) => {
        need(m.rx && m.rx.name && m.rx.dose === '', `${m.generic}: needs an rx block with a blank dose`)
        return {
          generic: m.generic,
          rx: m.rx,
          strengths: m.strength_verified ? m.strengths_india : [],
          // A dose is carried only when it was read from a source. Otherwise the app says so.
          verified: m.verified === true,
          doseGuide: m.verified === true ? m.dose_guide : '',
          max: m.verified === true ? m.max : '',
          indication: m.indication,
          monitoring: m.monitoring,
          prescriberNote: m.prescriber_note ?? '',
          note: m.note,
          quote: m.quote,
          sources: cite(m.source_ids),
          // The dose is cited to the guidelines only, not to the drug index used for tablet strengths.
          doseSources: m.source_ids.filter((id) => !/used only for/i.test(c.sources.find((s) => s.id === id).title)),
        }
      }),
      advice: c.advice.map((a) => ({ text: a.text, sources: cite(a.source_ids) })),
      caveats: c.caveats,
    })
  }
}
const text = `/* AUTO-GENERATED by scripts/build-protocols.mjs from reference-data/protocols/*.json. DO NOT EDIT BY HAND.
 * Guideline-based suggestions (investigations, medicines, advice) per condition. Reference
 * content only; no patient data. Change the JSON and run \`npm run build:protocols\`.
 */
/* oxlint-disable */
import type { Protocol } from './protocols'

export const PROTOCOL_DATA: Protocol[] = ${JSON.stringify(out, null, 1)}
`
writeFileSync(new URL('../src/lib/protocol-data.ts', import.meta.url), text)
console.log(`src/lib/protocol-data.ts written: ${out.length} protocols, ${out.reduce((n, p) => n + p.medicines.length, 0)} medicines, ${out.reduce((n, p) => n + p.sets.reduce((k, s) => k + s.items.length, 0), 0)} investigation items`)
